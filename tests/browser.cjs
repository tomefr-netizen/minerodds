const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8080');
  await page.waitForSelector('[data-coin]');
  assert.equal(await page.locator('[data-coin]').count(),8);
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  assert.ok(await page.locator('.brand svg').count());
  assert.ok((await page.locator('#table-body').innerText()).includes('>99.99%'));
  await page.screenshot({path:'/tmp/minerodds-desktop.png',fullPage:true});
  await page.locator('[data-coin="DGB"]').click();
  assert.ok(await page.locator('#detail').isVisible());
  const pixels=await page.locator('canvas').evaluate(canvas=>{
    const data=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
    let n=0;for(let i=3;i<data.length;i+=4)if(data[i]>0)n++;return n;
  });
  assert.ok(pixels>1000,'Probability chart must render');
  await page.locator('#pool-tab').click();
  assert.ok(await page.locator('#power').isVisible());
  await page.locator('#fee').fill('100');
  assert.ok((await page.locator('#table-body').innerText()).includes('-$0.07'));
  await page.locator('#fee').fill('1');
  await page.locator('#hashrate').fill('0');
  await page.locator('#solo-tab').click();
  assert.ok((await page.locator('#table-body').innerText()).includes('0%'));
  await page.locator('#hashrate').fill('-1');
  assert.ok(await page.locator('#input-error').isVisible());
  assert.ok(await page.locator('#export').isDisabled());
  await page.locator('#hashrate').fill('1');
  await page.locator('#search').fill('bitcoin cash');
  assert.equal(await page.locator('[data-coin]').count(),2);
  await page.locator('#search').fill('nothing-matches');
  assert.ok((await page.locator('#table-body').innerText()).includes('No coins match'));
  await page.locator('#search').fill('');
  await page.locator('#pool-tab').click();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export').click();
  const download=await downloadPromise;
  await download.saveAs('/tmp/minerodds-export.csv');
  const csv=require('node:fs').readFileSync('/tmp/minerodds-export.csv','utf8');
  assert.ok(csv.includes('netMonth'));
  assert.equal(csv.split('\r\n').length,9);
  await page.locator('#theme').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.screenshot({path:'/tmp/minerodds-light.png',fullPage:true});
  await page.reload();await page.waitForSelector('[data-coin]');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.locator('#theme').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-coin="DGB"]').click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const brokenImages=await page.locator('img').evaluateAll(images=>images.filter(img=>!img.complete||!img.naturalWidth).length);
  assert.equal(brokenImages,0);
  await page.screenshot({path:'/tmp/minerodds-mobile.png',fullPage:true});
  await page.locator('#pool-tab').click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'/tmp/minerodds-mobile-pool.png',fullPage:true});
  const snapshot=await (await page.request.get('http://127.0.0.1:8080/api/coins.php')).json();
  const sekRate=snapshot.exchange.rates.SEK;
  assert.ok(sekRate>0);
  const usdElectricity=Number(await page.locator('#electricity').inputValue());
  const btcUsd=await page.locator('[data-block-value="BTC"]').innerText();
  await page.locator('#currency').selectOption('SEK');
  assert.ok((await page.locator('[data-block-value="BTC"]').innerText()).startsWith('SEK'));
  assert.ok(Math.abs(Number(await page.locator('#electricity').inputValue())-usdElectricity*sekRate)<1e-9);
  assert.equal(await page.locator('#electricity-unit').innerText(),'SEK/kWh');
  assert.ok((await page.locator('#detail').innerText()).includes('Block value (before pool fees)'));
  const valueBeforeFee=await page.locator('[data-block-value="BTC"]').innerText();
  await page.locator('#fee').fill('100');
  assert.equal(await page.locator('[data-block-value="BTC"]').innerText(),valueBeforeFee,'Block value must not subtract pool fees');
  await page.locator('#fee').fill('1');
  await page.screenshot({path:'/tmp/minerodds-mobile-sek.png',fullPage:true});
  await page.reload();await page.waitForSelector('[data-coin]');
  assert.equal(await page.locator('#currency').inputValue(),'SEK');
  assert.ok(Math.abs(Number(await page.locator('#electricity').inputValue())-usdElectricity*sekRate)<1e-9);
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'/tmp/minerodds-desktop-sek.png',fullPage:true});
  const sekDownloadPromise=page.waitForEvent('download');
  await page.locator('#export').click();
  const sekDownload=await sekDownloadPromise;await sekDownload.saveAs('/tmp/minerodds-sek.csv');
  const csvRows=require('node:fs').readFileSync('/tmp/minerodds-sek.csv','utf8').split('\r\n').map(row=>row.split(',').map(value=>value.slice(1,-1)));
  const headers=csvRows[0], btcRow=csvRows.find(row=>row[0]==='BTC');
  assert.equal(btcRow[headers.indexOf('currency')],'SEK');
  const btc=snapshot.coins.find(coin=>coin.symbol==='BTC');
  assert.ok(Math.abs(Number(btcRow[headers.indexOf('blockValue')])-btc.reward*btc.price*sekRate)<1e-6);
  assert.ok(Math.abs(Number(btcRow[headers.indexOf('price')])-btc.price*sekRate)<1e-6);
  assert.equal(Number(btcRow[headers.indexOf('reward')]),btc.reward,'Native rewards must not be converted');
  await page.locator('#currency').selectOption('USD');
  assert.equal(await page.locator('[data-block-value="BTC"]').innerText(),btcUsd);
  assert.ok(Math.abs(Number(await page.locator('#electricity').inputValue())-usdElectricity)<1e-10);
  await page.locator('#currency').selectOption('SEK');
  await page.route('**/api/coins.php',route=>route.fulfill({json:{...snapshot,exchange:{rates:{USD:1},dates:{},stale:true}}}));
  await page.reload();await page.waitForSelector('[data-coin]');
  assert.equal(await page.locator('#currency').inputValue(),'USD');
  assert.ok((await page.locator('#currency-status').innerText()).includes('SEK rate unavailable'));
  await page.unroute('**/api/coins.php');
  await page.route('**/api/coins.php',route=>route.fulfill({json:{...snapshot,exchange:{...snapshot.exchange,stale:true}}}));
  await page.reload();await page.waitForSelector('[data-coin]');
  assert.equal(await page.locator('#currency').inputValue(),'SEK');
  assert.ok((await page.locator('#currency-status').innerText()).includes('cached rate is stale'));
  await page.unroute('**/api/coins.php');
  assert.equal((await page.request.get('http://127.0.0.1:8080/var/cache/snapshot.json')).status(),404);
  assert.equal((await page.request.get('http://127.0.0.1:8080/.git/config')).status(),404);
  assert.equal((await page.request.get('http://127.0.0.1:8080/.env')).status(),404);
  assert.deepEqual(errors,[]);
  console.log('Desktop/mobile, themes, chart, inputs, search, USD/SEK conversion, saved currency, CSV, missing/stale FX and cache access checks passed.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
